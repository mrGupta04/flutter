import 'package:flutter/material.dart';

/// Divider motif shown between title and price on [HealthPackageCard].
enum HealthPackageDividerStyle {
  ecg('assets/illustrations/ecg.svg'),
  shield('assets/illustrations/shield.svg');

  const HealthPackageDividerStyle(this.assetPath);

  final String assetPath;
}

/// Data model for premium health package / risk screening cards.
class HealthPackage {
  const HealthPackage({
    required this.id,
    required this.title,
    required this.price,
    required this.originalPrice,
    required this.discount,
    required this.color,
    required this.illustration,
    required this.popular,
    required this.testIds,
    this.dividerStyle = HealthPackageDividerStyle.ecg,
    this.badgeLabel,
  });

  final String id;
  final String title;
  final double price;
  final double originalPrice;
  final int discount;
  final Color color;
  final String illustration;
  final bool popular;
  final List<String> testIds;
  final HealthPackageDividerStyle dividerStyle;
  final String? badgeLabel;

  /// Very light tint derived from [color] for subtle radial gradients.
  Color get lightColor => Color.alphaBlend(
        color.withValues(alpha: 0.10),
        Colors.white,
      );
}

